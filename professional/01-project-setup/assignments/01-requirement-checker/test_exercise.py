# --- requirements --------------------------------------------------------------

def test_requirement_is_frozen(ex):
    req = ex.Requirement("httpx")
    assert (req.extras, req.specifiers, req.marker) == ((), (), None)
    with pytest.raises(dataclasses.FrozenInstanceError):
        req.name = "other"


def test_parse_simple_requirement(ex):
    assert ex.parse_requirement("rich") == ex.Requirement("rich")
    assert ex.parse_requirement("click>=8.1") == ex.Requirement("click", specifiers=(">=8.1",))


def test_parse_full_requirement(ex):
    line = 'HTTPX[http2] >=0.27, <1 ; python_version >= "3.10"  # client'
    assert ex.parse_requirement(line) == ex.Requirement(
        name="httpx",
        extras=("http2",),
        specifiers=(">=0.27", "<1"),
        marker='python_version >= "3.10"',
    )


def test_parse_requirement_normalises_and_sorts_extras(ex):
    req = ex.parse_requirement("Flask_SQLAlchemy[Async, Dev_Tools] == 3.1.1")
    assert req.name == "flask-sqlalchemy"
    assert req.extras == ("async", "dev-tools")
    assert req.specifiers == ("==3.1.1",)
    assert req.marker is None


def test_parse_requirement_with_spaces_inside_specifiers(ex):
    req = ex.parse_requirement("  django  >= 4.2 ,  < 6  ")
    assert req == ex.Requirement("django", specifiers=(">=4.2", "<6"))


@pytest.mark.parametrize("line", ["", "   ", "# only a comment", ">=1.0", "-pkg", "pkg >=1.0, nonsense", "pkg ==1.x"])
def test_parse_requirement_rejects(ex, line):
    with pytest.raises(ValueError):
        ex.parse_requirement(line)


def test_requirement_allows(ex):
    req = ex.parse_requirement("httpx>=0.27,<1")
    assert req.allows("0.27.2")
    assert req.allows("0.99")
    assert not req.allows("0.26.0")
    assert not req.allows("1.0")
    assert ex.Requirement("rich").allows("13.9.4")


# --- lock files ----------------------------------------------------------------

LOCK = """\
# generated by uv, do not edit
anyio==4.6.2
Certifi==2024.8.30

h11 == 0.14.0
httpx==0.27.2   # via the app
"""


def test_parse_lock(ex):
    assert ex.parse_lock(LOCK) == {
        "anyio": "4.6.2",
        "certifi": "2024.8.30",
        "h11": "0.14.0",
        "httpx": "0.27.2",
    }


def test_parse_lock_empty(ex):
    assert ex.parse_lock("") == {}
    assert ex.parse_lock("\n# nothing\n") == {}


@pytest.mark.parametrize("text, number", [
    ("anyio==4.6.2\nhttpx>=0.27\n", 2),
    ("anyio\n", 1),
    ("a==1\n\nb==\n", 3),
    ("==1.0\n", 1),
    ("a==1.x\n", 1),
])
def test_parse_lock_rejects(ex, text, number):
    with pytest.raises(ValueError, match=f"^line {number}: expected name==version$"):
        ex.parse_lock(text)


# --- check ---------------------------------------------------------------------

def test_check_all_good(ex):
    assert ex.check(["httpx>=0.27,<1", "anyio", "h11~=0.14.0"], LOCK) == []


def test_check_reports_problems_in_order(ex):
    problems = ex.check(["httpx>=0.27,<1", "rich", "click>=8.1"], "httpx==0.26.0\nclick==8.1.7\n")
    assert problems == [
        "httpx: locked 0.26.0 does not satisfy >=0.27,<1",
        "rich: missing from the lock file",
    ]


def test_check_skips_blank_and_comment_lines_and_ignores_markers(ex):
    requirements = ["", "# runtime", "Certifi ; sys_platform == 'win32'", "   ", "httpx >= 1.0"]
    assert ex.check(requirements, LOCK) == ["httpx: locked 0.27.2 does not satisfy >=1.0"]


def test_check_matches_normalised_names(ex):
    assert ex.check(["Zope.Interface>=6"], "zope_interface==7.1\n") == []
