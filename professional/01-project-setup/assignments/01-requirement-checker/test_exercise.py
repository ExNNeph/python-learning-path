import dataclasses

import pytest


# --- names and versions --------------------------------------------------------

@pytest.mark.parametrize("name, expected", [
    ("requests", "requests"),
    ("Flask_SQLAlchemy", "flask-sqlalchemy"),
    ("zope.interface", "zope-interface"),
    ("My__Weird-._Name", "my-weird-name"),
])
def test_normalize_name(ex, name, expected):
    assert ex.normalize_name(name) == expected


@pytest.mark.parametrize("text, expected", [
    ("1", (1,)),
    ("1.4.2", (1, 4, 2)),
    ("1.10.0", (1, 10)),
    ("2.0.0.0", (2,)),
    ("0", ()),
    ("1.0.1", (1, 0, 1)),
    ("  3.12 ", (3, 12)),
    ("2024.8.30", (2024, 8, 30)),
])
def test_parse_version(ex, text, expected):
    assert ex.parse_version(text) == expected


@pytest.mark.parametrize("text", ["", "  ", "1..2", "1.", ".1", "v1.0", "1.0rc1", "-1", "1.x", "1 .2"])
def test_parse_version_rejects(ex, text):
    with pytest.raises(ValueError, match="invalid version"):
        ex.parse_version(text)


def test_versions_compare_as_numbers(ex):
    v = ex.parse_version
    assert v("1.10") > v("1.9")
    assert v("1.0") == v("1.0.0")
    assert v("1.0.0") < v("1.0.1")
    assert sorted(["1.10", "1.2", "1.9.1", "1.0"], key=v) == ["1.0", "1.2", "1.9.1", "1.10"]


